package main

import (
	"database/sql"
	"fmt"
	"log/slog"
	"net/http"
	"os"
	"text/template"
	"time"

	"github.com/alexedwards/scs/postgresstore"
	"github.com/alexedwards/scs/sqlite3store"
	"github.com/alexedwards/scs/v2"
	"github.com/go-playground/form/v4"
	_ "github.com/lib/pq"
	_ "github.com/mattn/go-sqlite3"
	"github.com/rnemeth90/snippetbox/internal/models"
	"github.com/spf13/pflag"
)

var (
	addr      string
	dsn       string
	dbDriver  string
	debugMode bool
)

type application struct {
	logger         *slog.Logger
	db             *sql.DB
	snippets       models.SnippetModelInterface
	users          models.UserModelInterface
	templateCache  map[string]*template.Template
	formDecoder    *form.Decoder
	sessionManager *scs.SessionManager
	debugMode      bool
}

func init() {
	pflag.StringVar(&addr, "addr", ":4000", "address:port to listen on")
	pflag.BoolVar(&debugMode, "debug", false, "debug mode")
	pflag.StringVar(&dbDriver, "db-driver", envOrDefault("DB_DRIVER", "postgres"), "database driver (postgres or sqlite)")
	pflag.StringVar(&dsn, "dsn", envOrDefault("DB_DSN", ""), "database DSN (defaults to the configured driver)")
	pflag.Usage = usage
}

func envOrDefault(key, fallback string) string {
	if value := os.Getenv(key); value != "" {
		return value
	}
	return fallback
}

func usage() {
	pflag.PrintDefaults()
}

func main() {
	pflag.Parse()

	logger := slog.New(slog.NewTextHandler(os.Stdout, nil))

	db, err := openDB(dbDriver, dsn)
	if err != nil {
		logger.Error(err.Error())
		os.Exit(1)
	}
	defer db.Close()

	if err := initializeSchema(db, dbDriver); err != nil {
		logger.Error(err.Error())
		os.Exit(1)
	}

	templateCache, err := newTemplateCache()
	if err != nil {
		logger.Error(err.Error())
		os.Exit(1)
	}

	formDecoder := form.NewDecoder()

	sessionManager := scs.New()
	switch dbDriver {
	case "postgres":
		sessionManager.Store = postgresstore.New(db)
	case "sqlite":
		sessionManager.Store = sqlite3store.New(db)
	}
	sessionManager.Lifetime = 12 * time.Hour
	sessionManager.Cookie.Secure = true

	app := &application{
		logger:         logger,
		db:             db,
		templateCache:  templateCache,
		users:          &models.UserModel{DB: db, Dialect: dbDriver},
		snippets:       &models.SnippetModel{DB: db, Dialect: dbDriver},
		formDecoder:    formDecoder,
		sessionManager: sessionManager,
		debugMode:      debugMode,
	}

	server := http.Server{
		Addr:         addr,
		Handler:      app.routes(),
		ErrorLog:     slog.NewLogLogger(logger.Handler(), slog.LevelError),
		IdleTimeout:  time.Minute,
		ReadTimeout:  5 * time.Second,
		WriteTimeout: 10 * time.Second,
	}

	logger.Info("starting server", "addr", server.Addr)

	err = server.ListenAndServe()
	if err != nil && err != http.ErrServerClosed {
		logger.Error(err.Error())
		os.Exit(1)
	}
}

func openDB(driver, dsn string) (*sql.DB, error) {
	if driver != "postgres" && driver != "sqlite" {
		return nil, fmt.Errorf("unsupported database driver %q", driver)
	}
	if dsn == "" && driver == "postgres" {
		dsn = "postgres://web:pass@localhost/snippetbox?sslmode=disable"
	}
	if driver == "sqlite" {
		if dsn == "" {
			dsn = "snippetbox.db"
		}
		if !isSQLiteMemoryDB(dsn) && !hasSQLiteURI(dsn) && dsn != ":memory:" {
			dsn = "file:" + dsn + "?_busy_timeout=5000&_journal_mode=WAL&_loc=UTC"
		}
	}
	db, err := sql.Open(driverName(driver), dsn)
	if err != nil {
		return nil, err
	}
	if driver == "sqlite" {
		db.SetMaxOpenConns(1)
	}

	if err = db.Ping(); err != nil {
		db.Close()
		return nil, err
	}

	return db, nil
}

func driverName(driver string) string {
	if driver == "sqlite" {
		return "sqlite3"
	}
	return "postgres"
}

func isSQLiteMemoryDB(dsn string) bool {
	return dsn == ":memory:" || dsn == "file::memory:"
}

func hasSQLiteURI(dsn string) bool {
	return len(dsn) >= 5 && dsn[:5] == "file:"
}

func initializeSchema(db *sql.DB, driver string) error {
	usersID := "INTEGER PRIMARY KEY AUTOINCREMENT"
	passwordType := "BLOB"
	createdType := "DATETIME"
	snippetID := "INTEGER PRIMARY KEY AUTOINCREMENT"
	sessionDataType := "BLOB"
	sessionExpiryType := "REAL"
	if driver == "postgres" {
		usersID = "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
		passwordType = "BYTEA"
		createdType = "TIMESTAMPTZ"
		snippetID = "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
		sessionDataType = "BYTEA"
		sessionExpiryType = "TIMESTAMPTZ"
	}

	statements := []string{
		fmt.Sprintf(`CREATE TABLE IF NOT EXISTS users (
			id %s,
			name TEXT NOT NULL,
			email TEXT NOT NULL CONSTRAINT users_email_key UNIQUE,
			hashed_password %s NOT NULL,
			created %s NOT NULL
		)`, usersID, passwordType, createdType),
		fmt.Sprintf(`CREATE TABLE IF NOT EXISTS snippets (
			id %s,
			title TEXT NOT NULL,
			content TEXT NOT NULL,
			created %s NOT NULL,
			expires %s NOT NULL
		)`, snippetID, createdType, createdType),
		fmt.Sprintf(`CREATE TABLE IF NOT EXISTS sessions (
			token TEXT PRIMARY KEY,
			data %s NOT NULL,
			expiry %s NOT NULL
		)`, sessionDataType, sessionExpiryType),
	}
	for _, statement := range statements {
		if _, err := db.Exec(statement); err != nil {
			return fmt.Errorf("initialize database schema: %w", err)
		}
	}
	return nil
}
